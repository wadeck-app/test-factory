// Generates the build flows flows/03_build_<kind>.yml from one template: only the id, the commit prefix and the instructions
// differ per kind, the wiring is the same. Run `npm run generate:flows` after editing this file; CI fails when the files are stale.
//
//   node flows/lib/generate-build-flows.mjs [--check]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const flowsDirectory = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
import { BUILD_KINDS } from './kinds.mjs';

const VERSION = '0.4.1';

const kinds = {
	feature: {
		prefix: 'feat',
		description: 'a new capability',
		instructions: [
			'Implement the task as a new capability of the school app-module.',
			'Add unit tests for the new behaviour next to the code (*.test.ts).',
		],
		extraGate: '',
	},
	enhancement: {
		prefix: 'feat',
		description: 'an improvement of an existing capability',
		instructions: [
			'Improve the existing capability the task describes. Keep every existing route, view and stored data format working unless the task says otherwise.',
			'Extend the existing tests and add tests for the new behaviour.',
		],
		extraGate: '',
	},
	bug: {
		prefix: 'fix',
		description: 'a bug fix',
		instructions: [
			'Reproduce the bug first: add a test that fails because of the bug, then fix the code so that it passes.',
			'The change MUST include a new or changed test file (*.test.ts): the flow refuses a fix without one.',
		],
		extraGate: `      # A bug fix must come with a test that reproduces it.
      if ! { git diff --name-only origin/integration; git ls-files --others --exclude-standard; } | grep -qE '\\.(test|spec)\\.[cm]?[jt]sx?$'; then
        echo "A bug fix must include a new or changed test file (*.test.ts) that reproduces the bug. None is part of the change." >&2
        exit 1
      fi
`,
	},
};

function render(kind, { prefix, description, instructions, extraGate }) {
	return `# GENERATED by flows/lib/generate-build-flows.mjs, do not edit: change the generator and run \`npm run generate:flows\`.
# Build flow for ${description}. Manual run (the dispatcher normally starts it):
#   flow run flows/03_build_${kind}.yml -i taskId=<id> --wait
#
#   sync       host   slot on the task branch: new from origin/integration, or resumed from origin/<branch> with integration merged in
#   install    host   npm ci for the Linux VM, with the registry access of the host user (no token reaches the VM, no install scripts)
#   fetch_task host   task text for the model
#   implement  VM     model step, no git rights; its validation sub-step (gates) feeds failures back to it, up to 3 rounds
#     gates    VM     build, test, violations, app-module check (refused when the change touches a package.json or the lockfile)
#   commit     host   verify the model did not touch git, finish the merge if any, commit
#   push       host   push the task branch (the integrator fetches it from origin)

id: build_${kind}
version: '${VERSION}'
name: 'Build: ${description}'
description: 'Sync a pool slot, implement the task with a sandboxed model, gate it, commit and push the task branch'

requires: [sandbox]

workspace: { provider: pool, dir: C:/Workspace_Tooling, prefix: _test-factory_wt, count: 4 }

inputs:
  taskId: text

steps:
  - id: sync
    name: 'Put the slot on the task branch'
    type: script
    host: true
    captureOutput: stdout
    env:
      TASK_ID: \${{ inputs.taskId }}
    script: |
      set -euo pipefail
      bash C:/Workspace_Tooling/_test-factory/flows/lib/sync-branch.sh "$TASK_ID"

  - id: install
    name: 'Install the dependencies for the VM'
    type: script
    host: true
    depends: [sync]
    timeout: 600
    script: |
      set -euo pipefail
      bash C:/Workspace_Tooling/_test-factory/flows/lib/install-deps.sh

  - id: fetch_task
    name: 'Fetch the task text'
    type: script
    host: true
    captureOutput: stdout
    depends: [sync]
    env:
      TASK_ID: \${{ inputs.taskId }}
    script: |
      set -euo pipefail
      task show "$TASK_ID" -p test-factory

  - id: implement
    name: 'Implement the task'
    type: model
    model: sonnet
    depends: [fetch_task, install]
    tools: [read, write, edit, glob, grep, bash]
    # No interactive approval in a headless sandbox run: the VM and the git deny hooks are the guardrails.
    skipPermissions: true
    # Defense in depth: the sandbox has no git credentials and the commit is a host step (commit-branch.sh checks it again).
    toolHooks:
      - timing: before
        action: { type: deny, reason: 'git commit/push are done by the flow, never by the model', toolPattern: '*', argsContains: 'git commit' }
      - timing: before
        action: { type: deny, reason: 'git commit/push are done by the flow, never by the model', toolPattern: '*', argsContains: 'git push' }
    subStepStrategy: wait-all
    maxSubStepIterations: 3
    subStepFeedbackPrompt: |
      The checks of the flow failed on your work. Fix the code (never run git), the flow runs the checks again.
      \${{ subStepFeedback }}
    prompt: |
      You work in a git clone (your working directory) of the repository "test-factory", already on the task branch.
${instructions.map((line) => `      - ${line}`).join('\n')}
      - Only edit files under packages/. Follow the existing layout of packages/app-module-school (app-core app-module: views are YAML in src/dsl-views, backend in src/backend/index.ts).
      - The dependencies are already installed: you can run "npm run build", "npm test" and "npm run violations" yourself. Do not add or change dependencies (package.json, package-lock.json): the flow refuses such a change. The flow runs build, tests and violations again and sends you what failed.
      - Never run git commit, git push, git checkout or git reset: the flow commits for you.
      - Cover EVERY part of the task. For a page: add its entry in manifest.json, and in its view the create, edit (PUT) AND delete actions when the task says CRUD.
      - For every route you add, test the success path AND each refusal (400, 404, 409). For a deletion or an edit of something other records reference,
        decide what happens to them (refuse with 409, or cascade) and test it.
      - Before writing a helper, grep src/backend for an existing one; extract it instead of copying more than 5 lines.
      - Never hand-write typings for a library or a Node built-in: if a type is missing, say so in your final summary instead.
      - Before finishing, re-read the task's "Check" line and verify each point in the code.
      - Finish with a short summary of what you changed, then one line "Not verified: ..." listing what you could not check (for example how the DSL displays an error), or "Not verified: none".

      The first lines below are the state of your branch: its name, the commit you start from, "new" or "resume", then the files in conflict.
      "resume" means the branch already holds earlier work (see git log): continue from it. Files in conflict contain conflict markers
      (<<<<<<<, =======, >>>>>>>): resolve them by keeping the intent of both sides, and leave no marker in any file.
      \${{ steps.sync.outputs.stdout }}

      The task (JSON of the task tracker, follow its description literally):
      \${{ steps.fetch_task.outputs.stdout }}

  - id: gates
    name: 'Install, build, test, violations, app-module check (VM)'
    type: script
    shell: bash
    parent: implement
    timeout: 600
    script: |
      set -euo pipefail
      # The dependencies were installed on the host before the model ran: a changed manifest or lockfile would make them stale.
      CHANGED_MANIFESTS=$({ git diff --name-only origin/integration; git ls-files --others --exclude-standard; } | grep -E '(^|/)package(-lock)?\\.json$' || true)
      if [ -n "$CHANGED_MANIFESTS" ]; then
        echo "The change touches dependency files ($CHANGED_MANIFESTS). Adding or changing dependencies is not supported by the flow yet: revert these files and solve the task without a new dependency." >&2
        exit 1
      fi
${extraGate}      npm run build
      npm test
      npm run violations
      npm run check

  - id: commit
    name: 'Commit the change on the task branch'
    type: script
    host: true
    depends: [implement]
    env:
      TASK_ID: \${{ inputs.taskId }}
      SYNC: \${{ steps.sync.outputs.stdout }}
    script: |
      set -euo pipefail
      BASE=$(printf '%s\\n' "$SYNC" | sed -n 2p)
      MERGING=$(printf '%s\\n' "$SYNC" | sed -n 5p)
      bash C:/Workspace_Tooling/_test-factory/flows/lib/commit-branch.sh "$TASK_ID" "$BASE" ${prefix} "$MERGING"

  - id: push
    name: 'Push the task branch'
    type: script
    host: true
    depends: [commit]
    script: |
      set -euo pipefail
      bash C:/Workspace_Tooling/_test-factory/flows/lib/push-branch.sh
`;
}

const check = process.argv.includes('--check');
const unknown = process.argv.slice(2).filter((argument) => argument !== '--check');
if (unknown.length > 0) {
	console.error(`generate-build-flows: unknown argument(s): ${unknown.join(' ')}. Usage: node flows/lib/generate-build-flows.mjs [--check]`);
	process.exit(1);
}
// The flows and the dispatcher must agree on the kinds: kinds.mjs is the single list.
if (JSON.stringify(Object.keys(kinds)) !== JSON.stringify(BUILD_KINDS)) {
	console.error(`generate-build-flows: the kinds defined here (${Object.keys(kinds).join(', ')}) differ from flows/lib/kinds.mjs (${BUILD_KINDS.join(', ')}). Update both.`);
	process.exit(1);
}
let stale = 0;
for (const [kind, definition] of Object.entries(kinds)) {
	const file = path.join(flowsDirectory, `03_build_${kind}.yml`);
	const expected = render(kind, definition);
	if (check) {
		// A Windows checkout may have CRLF line endings: they are not a staleness.
		if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8').replaceAll('\r\n', '\n') !== expected) {
			stale += 1;
			console.error(`generate-build-flows: ${file} is stale or missing. Run: npm run generate:flows`);
		}
	} else {
		fs.writeFileSync(file, expected);
		console.log(`generate-build-flows: wrote ${path.relative(path.dirname(flowsDirectory), file)}`);
	}
}
if (stale > 0) process.exit(1);
